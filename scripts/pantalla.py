    pg.tap('#probador-x'); pg.wait_for_timeout(700)
    t1=pg.evaluate("document.querySelector('[data-cat=\"clasico-aros\"]').getBoundingClientRect().top")
    print('catalogo antes/despues', round(t0), round(t1))
    pg.reload(); pg.wait_for_timeout(1200); print('recarga scrollY', pg.evaluate("scrollY"))
    print('ERRS', errs); b.close()
