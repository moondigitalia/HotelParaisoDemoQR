from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=b.new_context(viewport={'width':375,'height':812},device_scale_factor=2,is_mobile=True,has_touch=True,locale='es-MX').new_page()
    errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:5055/?sinintro'); pg.wait_for_timeout(1500)
    pg.evaluate("localStorage.clear()"); pg.reload(); pg.wait_for_timeout(1500)
    print('inicio scrollY', pg.evaluate("scrollY"))
    pg.tap('[data-camino="catalogo"]'); pg.wait_for_timeout(900); pg.screenshot(path='/tmp/claude-0/e1.png')
    pg.tap('[data-nav="siguiente"]'); pg.wait_for_timeout(700)
    pg.tap('[data-nav="siguiente"]'); pg.wait_for_timeout(700)
    pg.fill('#f-nombre','Juanpy'); pg.fill('#f-numero','11'); pg.wait_for_timeout(600)
    pg.evaluate("document.querySelector('#tablero').scrollTop=400"); pg.wait_for_timeout(500)
    top=pg.evaluate("document.querySelector('#escenario').getBoundingClientRect().top")
    pg.screenshot(path='/tmp/claude-0/e2.png')
    pg.mouse.wheel(0,600); pg.wait_for_timeout(300)
    print('escenario top', round(top), 'body fijo', pg.evaluate("getComputedStyle(document.body).position"), 'ancho', pg.evaluate("document.documentElement.scrollWidth"))
    pg.tap('#probador-x'); pg.wait_for_timeout(700)
    print('tras cerrar scrollY', pg.evaluate("scrollY"), 'tablero', pg.inner_text('#tablero')[:40].replace('\n',' | '))
